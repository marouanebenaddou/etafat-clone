// Builds the static website for classic hosting (etafat.ma: LiteSpeed/Apache, uploaded by FTP) into site-www/.
// Same pages as the Vercel site (etafat-new.vercel.app), minus the event apps — the /evenement borne and the
// /xr VR experience — and their assets: no main-site page links to them.
// Run: node scripts/build-site-export.mjs   (SKIP_BUILD=1 reuses an existing out/)
// Then upload with scripts/deploy-etafat-ma.sh.
import { execSync } from "node:child_process";
import { cpSync, rmSync, writeFileSync, readdirSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const out = path.join(root, "out");
const www = path.join(root, "site-www");

if (!process.env.SKIP_BUILD) {
  console.log("▶ Static export (KIOSK_EXPORT=1 next build)…");
  execSync("npx --no-install next build", { stdio: "inherit", env: { ...process.env, KIOSK_EXPORT: "1" } });
}

// event apps and what only they use (paths relative to out/)
const EXCLUDE = [
  "evenement", "xr", "etafat/evenement", "etafat/presence/banners", "vendor",
  "sw-evenement.js", "evenement.webmanifest", ".well-known", // .well-known: the VR TWA's asset links (Vercel domain)
];
// files in public/ that git doesn't track (films, Cité maquette, loose photos) never go online — as on Vercel
const untracked = new Set(
  execSync("git ls-files -o public && git ls-files -o -i --exclude-standard public", { encoding: "utf8" })
    .split("\n").filter(Boolean).map((f) => f.replace(/^public\//, "")),
);

console.log("▶ Assembling site-www/…");
rmSync(www, { recursive: true, force: true });
cpSync(out, www, {
  recursive: true,
  filter: (src) => {
    const rel = path.relative(out, src).split(path.sep).join("/");
    if (!rel) return true;
    if (EXCLUDE.some((e) => rel === e || rel.startsWith(e + "/"))) return false;
    if (untracked.has(rel)) return false;
    return true;
  },
});

// LiteSpeed/Apache rules. Kept to directives every shared host allows (no `Options`, which some refuse with a
// 500). They also apply to the hosting's untouched sauvegarde/ folder, hence index.php stays a directory index.
writeFileSync(path.join(www, ".htaccess"), `# ETAFAT — static site (Next.js export), generated by scripts/build-site-export.mjs
DirectoryIndex index.html index.php
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  # HTTPS everywhere
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !=https
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
</IfModule>

<IfModule mod_mime.c>
  AddType application/manifest+json .webmanifest
  AddType video/mp4 .mp4
  AddType image/webp .webp
</IfModule>

# pages and navigation payloads: always revalidate, so a new upload shows at once
<IfModule mod_headers.c>
  <FilesMatch "\\.(html|txt)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/jpeg "access plus 30 days"
  ExpiresByType image/png "access plus 30 days"
  ExpiresByType image/webp "access plus 30 days"
  ExpiresByType image/svg+xml "access plus 30 days"
  ExpiresByType video/mp4 "access plus 30 days"
</IfModule>
`);
// hashed JS/CSS/font chunks never change under the same name
writeFileSync(path.join(www, "_next/static/.htaccess"), `<IfModule mod_headers.c>
  Header set Cache-Control "public, max-age=31536000, immutable"
</IfModule>
`);

const count = (d) => readdirSync(d, { withFileTypes: true }).reduce((s, e) => s + (e.isDirectory() ? count(path.join(d, e.name)) : 1), 0);
const size = execSync(`du -sh "${www}"`, { encoding: "utf8" }).split("\t")[0];
console.log(`✓ site-www/ ready — ${count(www)} files, ${size}. Upload: scripts/deploy-etafat-ma.sh`);
